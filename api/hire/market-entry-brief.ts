// POST|GET /api/hire/market-entry-brief — $10.00 x402. Deterministic composition, no new LLM:
// country-risk + sector supply-chain risk + regulatory preview + macro regime (+ trade-tension).
import type { VercelRequest, VercelResponse } from '@vercel/node';
import { handlePaymentGate } from '../../lib/x402.js';
import { paidCacheArm } from '../../lib/paid-cache.js';
import { TASK_TYPES, readInput, validateAndQuote, fleetCall, PAID_ERROR_NOTE, safeJsonBlock, fenceSafe, type ComponentResult } from '../../lib/hire.js';

const T = TASK_TYPES['market-entry-brief'];

function hasPaymentSignature(req: VercelRequest): boolean {
  const h = req.headers['payment-signature'] ?? req.headers['PAYMENT-SIGNATURE' as never];
  return typeof h === 'string' && h.length > 0;
}

async function handlerImpl(req: VercelRequest, res: VercelResponse): Promise<void> {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, PAYMENT-SIGNATURE');
  res.setHeader('Access-Control-Expose-Headers', 'PAYMENT-REQUIRED, PAYMENT-RESPONSE');
  if (req.method === 'OPTIONS') { res.status(204).end(); return; }

  let input: Record<string, unknown>;
  try {
    input = readInput(req.query as Record<string, unknown>, req.body);
  } catch {
    res.status(400).json({ error: 'bad_request', message: 'Could not parse request body as JSON.', not_charged: true });
    return;
  }

  // Bare probe (unsigned) → 402 challenge for indexers. Declined-input validation on signed path only.
  if (hasPaymentSignature(req)) {
    const pre = validateAndQuote('market-entry-brief', { ...input, task_type: 'market-entry-brief' });
    if (!pre.ok) { res.status(400).json({ declined: true, reason: pre.declined_reason, not_charged: true }); return; }
  }

  const gate = await handlePaymentGate(req.headers, req.url ?? '/api/hire/market-entry-brief', T.amount, T.summary, T.tags, {
    queryParams: T.queryParams,
    outputExample: T.outputExample,
  });
  if (!gate.ok) { Object.entries(gate.headers).forEach(([k, v]) => res.setHeader(k, v)); res.status(gate.status).json(gate.body); return; }

  const quote = validateAndQuote('market-entry-brief', { ...input, task_type: 'market-entry-brief' });
  if (!quote.ok) {
    console.error('[FAIL] market-entry-brief: settled request failed validation (should be unreachable)', quote.declined_reason);
    res.status(400).json({ declined: true, reason: quote.declined_reason });
    return;
  }
  const { sector, target_country, home_country, size } = quote.normalized_input as Record<string, string | undefined>;

  const enc = encodeURIComponent;
  const calls: Record<string, Promise<ComponentResult>> = {
    country_risk: fleetCall(`https://geopoliticalpulse.theaslangroupllc.com/api/geopolitical/country-risk?country=${enc(target_country!)}`),
    supply_chain: fleetCall(`https://geopoliticalpulse.theaslangroupllc.com/api/geopolitical/supply-chain-risk?sector=${enc(sector!)}`),
    regulatory: fleetCall(
      `https://compliancepulse.theaslangroupllc.com/api/comply/scan-lite?country=${enc(target_country!)}&sector=${enc(sector!)}&activities=${enc(`market entry, sales and distribution of ${sector}`)}${size ? `&size=${enc(size)}` : ''}`,
    ),
    macro_regime: fleetCall('https://macropulse.theaslangroupllc.com/api/regime'),
    trade_tension: home_country
      ? fleetCall(`https://geopoliticalpulse.theaslangroupllc.com/api/geopolitical/trade-tension?country_a=${enc(home_country)}&country_b=${enc(target_country!)}`)
      : Promise.resolve<ComponentResult>({ status: 'skipped', note: 'pass home_country for bilateral trade-tension analysis' }),
  };

  const keys = Object.keys(calls);
  const settled = await Promise.all(Object.values(calls));
  const components: Record<string, ComponentResult> = {};
  keys.forEach((k, i) => (components[k] = settled[i]));

  const ran = keys.filter((k) => components[k].status !== 'skipped');
  const failed = ran.filter((k) => components[k].status === 'failed');
  if (failed.length === ran.length) {
    console.error('[FAIL] market-entry-brief: ALL components failed', { sector, target_country, failed });
    res.status(500).json({ error: 'all_components_failed', components, message: PAID_ERROR_NOTE });
    return;
  }

  const subject = `${sector} → ${target_country}`;
  const lines: string[] = [
    `# Market Entry Brief — ${fenceSafe(subject)}`,
    '',
    `Generated by PulseNetwork Hire-the-Fleet (market-entry-brief, $${T.price_usd.toFixed(2)}). Deterministic composition of live engines; each section reports its own source status.`,
    '',
  ];
  const summarize = (k: string, title: string): void => {
    const c = components[k];
    lines.push(`## ${title}`);
    if (c.status === 'skipped') lines.push(`_Skipped: ${fenceSafe(String(c.note))}_`);
    else if (c.status === 'failed') lines.push(`**SOURCE FAILED** (${fenceSafe(String(c.note))}) — this section is missing, not clean. See coverage.`);
    else lines.push(safeJsonBlock(c.data));
    lines.push('');
  };
  summarize('country_risk', `Country Risk — ${target_country}`);
  summarize('supply_chain', `Supply-Chain Geopolitical Risk — ${sector}`);
  summarize('regulatory', `Regulatory Applicability Preview — ${target_country}`);
  summarize('macro_regime', 'Global Macro Regime Context');
  summarize('trade_tension', home_country ? `Trade Tension — ${home_country} ↔ ${target_country}` : 'Trade Tension');
  lines.push('## Coverage', ...keys.map((k) => `- ${k}: ${components[k].status}${components[k].note ? ` (${components[k].note})` : ''}`));
  lines.push('', '_A failed section means the underlying engine was unavailable — it never means "no findings". Contact info@theaslangroupllc.com with your payment tx for credits on failed sections._');

  res.setHeader('Cache-Control', 'private, no-store');
  res.setHeader('PAYMENT-RESPONSE', gate.settlementHeader);
  paidCacheArm(req, res);
  res.status(200).json({
    task_type: 'market-entry-brief',
    subject,
    components,
    coverage: { ran: ran.length, ok: ran.length - failed.length, failed: failed.length, skipped: keys.length - ran.length },
    markdown: lines.join('\n'),
  });
}

export default async function handler(req: VercelRequest, res: VercelResponse): Promise<void> {
  try {
    await handlerImpl(req, res);
  } catch (err) {
    console.error('[FAIL] hire/market-entry-brief unhandled', { url: req.url, err });
    if (!res.headersSent) res.status(500).json({ error: 'task_failed', message: PAID_ERROR_NOTE });
  }
}
